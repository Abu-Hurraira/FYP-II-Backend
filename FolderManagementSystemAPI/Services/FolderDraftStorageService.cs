using System.Globalization;
using System.Text.Json;
using FolderManagementSystemAPI.DTOs;

namespace FolderManagementSystemAPI.Services;

public sealed class FolderDraftManifest
{
    public List<FolderDraftFileEntry> Files { get; set; } = new();
    public int NextFileId { get; set; } = -1;
}

public sealed class FolderDraftFileEntry
{
    public int FileId { get; set; }
    public int TemplateItemId { get; set; }
    public string TemplateCode { get; set; } = string.Empty;
    public string FileName { get; set; } = string.Empty;
    public string FilePath { get; set; } = string.Empty;
    public string FileCategory { get; set; } = string.Empty;
    public int UploadedByUserId { get; set; }
    public DateTime UploadedAt { get; set; }
    public bool IsAutoGenerated { get; set; }
    public string? ContentPreview { get; set; }
}

public class FolderDraftStorageService
{
    private readonly IWebHostEnvironment _environment;
    private static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = true };
    private static readonly object ManifestLock = new();

    public FolderDraftStorageService(IWebHostEnvironment environment)
    {
        _environment = environment;
    }

    public string GetAbsolutePath(string relativePath) =>
        Path.Combine(_environment.ContentRootPath, relativePath.Replace('/', Path.DirectorySeparatorChar));

    private string GetDraftRoot(int offeredCourseId) =>
        Path.Combine(_environment.ContentRootPath, "src", "FolderDrafts", offeredCourseId.ToString(CultureInfo.InvariantCulture));

    private string GetManifestPath(int offeredCourseId) =>
        Path.Combine(GetDraftRoot(offeredCourseId), "manifest.json");

    public FolderDraftManifest LoadManifest(int offeredCourseId)
    {
        lock (ManifestLock)
        {
            var path = GetManifestPath(offeredCourseId);
            if (!File.Exists(path))
            {
                return new FolderDraftManifest();
            }

            var json = File.ReadAllText(path);
            return JsonSerializer.Deserialize<FolderDraftManifest>(json, JsonOptions) ?? new FolderDraftManifest();
        }
    }

    private void SaveManifest(int offeredCourseId, FolderDraftManifest manifest)
    {
        lock (ManifestLock)
        {
            var root = GetDraftRoot(offeredCourseId);
            Directory.CreateDirectory(root);
            var path = GetManifestPath(offeredCourseId);
            File.WriteAllText(path, JsonSerializer.Serialize(manifest, JsonOptions));
        }
    }

    public bool HasDraftContent(int offeredCourseId) =>
        LoadManifest(offeredCourseId).Files.Count > 0;

    public List<(string TemplateCode, string Category, int Count)> GetCategoryCounts(int offeredCourseId)
    {
        return LoadManifest(offeredCourseId)
            .Files
            .GroupBy(file => new { file.TemplateCode, file.FileCategory })
            .Select(group => (group.Key.TemplateCode, group.Key.FileCategory, group.Count()))
            .ToList();
    }

    public List<CourseFolderFileDto> ListFiles(int offeredCourseId, int templateItemId)
    {
        return LoadManifest(offeredCourseId)
            .Files
            .Where(file => file.TemplateItemId == templateItemId)
            .OrderByDescending(file => file.UploadedAt)
            .Select(file => new CourseFolderFileDto
            {
                FileId = file.FileId,
                DirectoryId = -file.TemplateItemId,
                FileName = file.FileName,
                FilePath = file.FilePath,
                FileCategory = file.FileCategory,
                Remarks = file.IsAutoGenerated ? "Auto-generated" : null,
                ContentPreview = file.IsAutoGenerated ? file.ContentPreview : null,
                UploadedAt = file.UploadedAt
            })
            .ToList();
    }

    public FolderDraftFileEntry? GetFile(int offeredCourseId, int fileId)
    {
        return LoadManifest(offeredCourseId).Files.FirstOrDefault(file => file.FileId == fileId);
    }

    public FolderDraftFileEntry AddFile(
        int offeredCourseId,
        int templateItemId,
        string templateCode,
        int uploadedByUserId,
        string fileCategory,
        string originalFileName,
        Stream fileStream)
    {
        var manifest = LoadManifest(offeredCourseId);
        var fileId = manifest.NextFileId;
        manifest.NextFileId -= 1;

        var safeOriginalName = SanitizeFileName(originalFileName);
        var storedFileName = $"{DateTime.UtcNow:yyyyMMddHHmmssfff}_{safeOriginalName}";
        var relativeDirectory = $"src/FolderDrafts/{offeredCourseId}/{templateItemId}";
        var relativeFilePath = $"{relativeDirectory}/{storedFileName}";
        var absoluteDirectory = GetAbsolutePath(relativeDirectory);
        var absoluteFilePath = GetAbsolutePath(relativeFilePath);

        Directory.CreateDirectory(absoluteDirectory);

        using (var output = new FileStream(absoluteFilePath, FileMode.Create))
        {
            fileStream.CopyTo(output);
        }

        var entry = new FolderDraftFileEntry
        {
            FileId = fileId,
            TemplateItemId = templateItemId,
            TemplateCode = templateCode,
            FileName = storedFileName,
            FilePath = relativeFilePath,
            FileCategory = fileCategory,
            UploadedByUserId = uploadedByUserId,
            UploadedAt = DateTime.UtcNow
        };

        manifest.Files.Add(entry);
        SaveManifest(offeredCourseId, manifest);
        return entry;
    }

    public bool DeleteFile(int offeredCourseId, int fileId)
    {
        var manifest = LoadManifest(offeredCourseId);
        var entry = manifest.Files.FirstOrDefault(file => file.FileId == fileId);

        if (entry == null)
        {
            return false;
        }

        var absolutePath = GetAbsolutePath(entry.FilePath);
        if (File.Exists(absolutePath))
        {
            File.Delete(absolutePath);
        }

        manifest.Files.Remove(entry);
        SaveManifest(offeredCourseId, manifest);
        return true;
    }

    public FolderDraftFileEntry UpsertAutoGeneratedPdfFile(
        int offeredCourseId,
        int templateItemId,
        string templateCode,
        int uploadedByUserId,
        string fileCategory,
        string content,
        string baseFileName,
        string pdfTitle)
    {
        var manifest = LoadManifest(offeredCourseId);
        var existing = manifest.Files
            .Where(file =>
                file.IsAutoGenerated &&
                file.TemplateItemId == templateItemId &&
                file.FileCategory == fileCategory)
            .ToList();

        foreach (var old in existing)
        {
            var absolutePath = GetAbsolutePath(old.FilePath);
            if (File.Exists(absolutePath))
            {
                File.Delete(absolutePath);
            }

            manifest.Files.Remove(old);
        }

        var safeBaseName = SanitizeFileName(baseFileName);
        if (!safeBaseName.EndsWith(".pdf", StringComparison.OrdinalIgnoreCase))
        {
            safeBaseName += ".pdf";
        }

        var relativeDirectory = $"src/FolderDrafts/{offeredCourseId}/{templateItemId}";
        var relativeFilePath = $"{relativeDirectory}/{safeBaseName}";
        var absoluteDirectory = GetAbsolutePath(relativeDirectory);
        var absoluteFilePath = GetAbsolutePath(relativeFilePath);

        Directory.CreateDirectory(absoluteDirectory);
        var pdfBytes = TextPdfGenerator.Generate(pdfTitle, content);
        File.WriteAllBytes(absoluteFilePath, pdfBytes);

        var entry = new FolderDraftFileEntry
        {
            FileId = manifest.NextFileId,
            TemplateItemId = templateItemId,
            TemplateCode = templateCode,
            FileName = safeBaseName,
            FilePath = relativeFilePath,
            FileCategory = fileCategory,
            UploadedByUserId = uploadedByUserId,
            UploadedAt = DateTime.UtcNow,
            IsAutoGenerated = true,
            ContentPreview = content
        };

        manifest.NextFileId -= 1;
        manifest.Files.Add(entry);
        SaveManifest(offeredCourseId, manifest);
        return entry;
    }

    public void RemoveAutoGeneratedFiles(int offeredCourseId, int templateItemId, string fileCategory)
    {
        var manifest = LoadManifest(offeredCourseId);
        var existing = manifest.Files
            .Where(file =>
                file.IsAutoGenerated &&
                file.TemplateItemId == templateItemId &&
                string.Equals(file.FileCategory, fileCategory, StringComparison.OrdinalIgnoreCase))
            .ToList();

        if (existing.Count == 0)
        {
            return;
        }

        foreach (var old in existing)
        {
            var absolutePath = GetAbsolutePath(old.FilePath);
            if (File.Exists(absolutePath))
            {
                File.Delete(absolutePath);
            }

            manifest.Files.Remove(old);
        }

        SaveManifest(offeredCourseId, manifest);
    }

    public void RemoveAllAutoGeneratedFiles(int offeredCourseId)
    {
        var manifest = LoadManifest(offeredCourseId);
        var existing = manifest.Files.Where(file => file.IsAutoGenerated).ToList();
        if (existing.Count == 0)
        {
            return;
        }

        foreach (var old in existing)
        {
            var absolutePath = GetAbsolutePath(old.FilePath);
            if (File.Exists(absolutePath))
            {
                File.Delete(absolutePath);
            }

            manifest.Files.Remove(old);
        }

        SaveManifest(offeredCourseId, manifest);
    }

    public void Clear(int offeredCourseId)
    {
        lock (ManifestLock)
        {
            var root = GetDraftRoot(offeredCourseId);
            if (Directory.Exists(root))
            {
                Directory.Delete(root, true);
            }
        }
    }

    private static string SanitizeFileName(string fileName)
    {
        var invalid = Path.GetInvalidFileNameChars();
        var cleaned = new string(fileName.Select(ch => invalid.Contains(ch) ? '_' : ch).ToArray());
        return string.IsNullOrWhiteSpace(cleaned) ? "upload.pdf" : cleaned;
    }
}

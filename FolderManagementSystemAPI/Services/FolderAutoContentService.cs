    private static List<WeeklyPlanWordGenerator.WeekRow> BuildWeeklyOutlineRows(List<TopicNode> roots)
    {
        var rows = new List<WeeklyPlanWordGenerator.WeekRow>();
        foreach (var group in roots
            .GroupBy(t => t.WeekNo ?? 999)
            .OrderBy(g => g.Key))
        {
            var lectures = new List<WeeklyPlanWordGenerator.OutlineLine>();
            var labs = new List<WeeklyPlanWordGenerator.OutlineLine>();
            foreach (var root in group.OrderBy(t => t.DisplayOrder ?? 999).ThenBy(t => t.TopicId))
            {
                AppendOutlineNode(root, lectures, labs, labColumn: WeeklyPlanWordGenerator.IsLabTitle(root.TopicTitle), level: 0);
            }

            if (lectures.Count == 0 && labs.Count == 0)
            {
                continue;
            }

            var weekNo = group.Key == 999 ? "—" : group.Key.ToString("00");
            rows.Add(new WeeklyPlanWordGenerator.WeekRow(weekNo, lectures, labs));
        }

        return rows;
    }

    private static void AppendOutlineNode(
        TopicNode node,
        List<WeeklyPlanWordGenerator.OutlineLine> lectures,
        List<WeeklyPlanWordGenerator.OutlineLine> labs,
        bool labColumn,
        int level)
    {
        var thisIsLab = labColumn || WeeklyPlanWordGenerator.IsLabTitle(node.TopicTitle);
        var target = thisIsLab ? labs : lectures;
        var useLevel = thisIsLab && !labColumn ? 0 : level;

        if (!IsWeekOnlyTitle(node.TopicTitle))
        {
            target.Add(new WeeklyPlanWordGenerator.OutlineLine(
                useLevel,
                node.TopicTitle,
                Bold: useLevel == 0));
            useLevel++;
        }

        foreach (var child in node.Children.OrderBy(c => c.DisplayOrder ?? 999).ThenBy(c => c.TopicId))
        {
            AppendOutlineNode(child, lectures, labs, thisIsLab, useLevel);
        }
    }

    private static bool IsWeekOnlyTitle(string? title)
    {
        var text = (title ?? string.Empty).Trim();
        if (!text.StartsWith("week", StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }

        var rest = text[4..].Trim().TrimStart(':', '-', '.').Trim();
        return int.TryParse(rest, out _);
    }


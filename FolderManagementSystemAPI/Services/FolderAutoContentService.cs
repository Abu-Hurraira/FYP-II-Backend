    private async Task<byte[]?> BuildCloGaMappingDocxAsync(
        OfferedCourse oc,
        int programCourseId,
        int sessionId,
        TeacherPermissionFlagsDto permissions)
    {
        var programId = oc.Section.Session.ProgramId;
        var plos = await _context.Plos
            .AsNoTracking()
            .Where(p => p.ProgramId == programId)
            .ToListAsync();
        if (plos.Count == 0)
        {
            return null;
        }

        plos = plos
            .OrderBy(p =>
            {
                var match = System.Text.RegularExpressions.Regex.Match(p.Plocode ?? string.Empty, @"\d+");
                return match.Success && int.TryParse(match.Value, out var n) ? n : int.MaxValue;
            })
            .ThenBy(p => p.Ploid)
            .ToList();

        var cloVisible = _contentSubmissionService.VisibleContentStatuses(permissions.CanManageClos);
        var clos = await _context.Clos
            .AsNoTracking()
            .Where(c => c.ProgramCourseId == programCourseId && c.SessionId == sessionId)
            .Where(c => c.ContentStatus == ContentStatuses.Approved)
            .OrderBy(c => c.Clocode)
            .ToListAsync();
        if (clos.Count == 0)
        {
            clos = await _context.Clos
                .AsNoTracking()
                .Where(c => c.ProgramCourseId == programCourseId && c.SessionId == sessionId)
                .Where(c => cloVisible.Contains(c.ContentStatus))
                .OrderBy(c => c.Clocode)
                .ToListAsync();
        }

        if (clos.Count == 0)
        {
            return null;
        }

        var mappings = await _context.Ploclomappings
            .AsNoTracking()
            .Where(m =>
                m.ProgramCourseId == programCourseId &&
                m.SessionId == sessionId &&
                m.ContentStatus == ContentStatuses.Approved &&
                m.Percentage != null &&
                m.Percentage > 0)
            .ToListAsync();

        var ploLetters = plos
            .Select((plo, index) => (plo.Ploid, Letter: CloGaMappingWordGenerator.LetterForPlo(plo.Plocode, index)))
            .ToList();
        var letterByPloId = ploLetters.ToDictionary(x => x.Ploid, x => x.Letter);
        var mapped = mappings
            .GroupBy(m => m.Cloid)
            .ToDictionary(
                g => g.Key,
                g => g.Select(m => letterByPloId.TryGetValue(m.Ploid, out var letter) ? letter : null)
                    .Where(letter => !string.IsNullOrWhiteSpace(letter))
                    .Select(letter => letter!)
                    .ToHashSet(StringComparer.OrdinalIgnoreCase) as IReadOnlySet<string>);

        var outcomes = ploLetters
            .Select(item =>
            {
                var plo = plos.First(p => p.Ploid == item.Ploid);
                return new CloGaMappingWordGenerator.ProgramOutcome(item.Letter, plo.Plodescription ?? string.Empty);
            })
            .ToList();

        var cloRows = clos
            .Select((clo, index) =>
            {
                mapped.TryGetValue(clo.Cloid, out var letters);
                return new CloGaMappingWordGenerator.CloRow(
                    CloGaMappingWordGenerator.NumberForClo(clo.Clocode, index),
                    clo.Clodescription ?? clo.Clocode,
                    letters ?? new HashSet<string>(StringComparer.OrdinalIgnoreCase));
            })
            .ToList();

        var programName = oc.Section.Session.Program?.ProgramCode
            ?? oc.Section.Session.Program?.ProgramName
            ?? "Program";

        return CloGaMappingWordGenerator.Generate(
            programName,
            oc.Course.CourseTitle,
            oc.Course.CourseCode ?? string.Empty,
            outcomes,
            cloRows);
    }


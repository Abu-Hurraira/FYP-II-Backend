    public static bool IsAutoManagedTemplate(string templateCode) =>
        AutoManagedTemplateCodes.Contains(templateCode);

    public static bool IsHiddenSubmitTemplate(string? templateCode) =>
        !string.IsNullOrWhiteSpace(templateCode)
        && HiddenSubmitTemplateCodes.Contains(templateCode);

    public static bool IsProtectedGeneratedFile(string? fileName, string? templateCode)
    {
        if (!string.IsNullOrWhiteSpace(fileName)
            && fileName.StartsWith("FCAR-", StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        return string.Equals(templateCode, "o", StringComparison.OrdinalIgnoreCase);
    }

    public static bool IsJunkAutoOrSeed(string? remarks, string? fileName = null, string? templateCode = null)
    {
        if (IsProtectedGeneratedFile(fileName, templateCode))
        {
            return false;
        }

        var text = remarks ?? string.Empty;
        return string.Equals(text, AutoGeneratedRemark, StringComparison.OrdinalIgnoreCase)
               || text.Contains("AutoGenerated=1", StringComparison.OrdinalIgnoreCase)
               || text.Contains("demo folder seed", StringComparison.OrdinalIgnoreCase);
    }

    public async Task<string> GetPreviewForTemplateAsync(
        int offeredCourseId,
        int teacherUserId,
        string templateCode)
    {
        var oc = await _context.OfferedCourses
            .Include(x => x.Course)
            .Include(x => x.Section)
                .ThenInclude(s => s.Session)
            .FirstOrDefaultAsync(x => x.OfferedCourseId == offeredCourseId);

        if (oc == null)
        {
            return string.Empty;
        }

        var programCourseId = await _permissionService.EnsureProgramCourseAsync(
            oc.Section.Session.ProgramId,
            oc.CourseId);
        var sessionId = oc.Section.SessionId;
        var permissions = await _permissionService.GetTeacherFlagsAsync(teacherUserId, programCourseId);

        return templateCode.ToLowerInvariant() switch
        {
            "a" => await BuildCourseObjectivesContentAsync(programCourseId, sessionId, permissions),
            "b" => await BuildCloTaskMappingContentAsync(programCourseId, sessionId),
            "d" => await BuildWeeklyPlanContentAsync(offeredCourseId, programCourseId, sessionId, permissions),
            "c" => await BuildCourseContentsSummaryAsync(programCourseId, sessionId, permissions),
            _ => string.Empty
        };
    }


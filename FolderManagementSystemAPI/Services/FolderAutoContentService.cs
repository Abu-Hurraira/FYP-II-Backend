    /// <summary>
    /// Writes the CLO-GA mapping Word file into submitted folder template b.
    /// </summary>
    public async Task PublishCloTaskMappingToFolderAsync(int offeredCourseId, int teacherUserId)
    {
        var oc = await _context.OfferedCourses
            .Include(x => x.Course)
            .Include(x => x.Section)
                .ThenInclude(s => s.Session)
                    .ThenInclude(s => s.Program)
            .FirstOrDefaultAsync(x => x.OfferedCourseId == offeredCourseId);

        if (oc == null)
        {
            throw new InvalidOperationException("Offered course not found.");
        }

        var programCourseId = await _permissionService.EnsureProgramCourseAsync(
            oc.Section.Session.ProgramId,
            oc.CourseId);
        var sessionId = oc.Section.SessionId;

        var flags = await _permissionService.GetTeacherFlagsAsync(teacherUserId, programCourseId);
        if (!flags.CanManageCloPloMapping && !flags.CanManageCloTaskMapping && !flags.CanManageClos)
        {
            throw new InvalidOperationException("You do not have permission to publish CLO-GA mapping.");
        }

        var templates = await LoadTemplateItemsAsync();
        var folderRecord = await _folderProvisioning.EnsureMasterFolderAsync(
            offeredCourseId,
            teacherUserId);

        await RemoveAllTemplateCategoryFilesAsync(
            folderRecord.CourseFolderId, templates, "b", "CLO-Task Mapping");

        var cloGaDocx = await BuildCloGaMappingDocxAsync(
            oc, programCourseId, sessionId, flags);
        if (cloGaDocx is not { Length: > 0 })
        {
            throw new InvalidOperationException("CLO-GA mapping Word file could not be generated yet.");
        }

        await UpsertPhysicalPdfAsync(
            folderRecord.CourseFolderId,
            templates,
            "b",
            teacherUserId,
            "CLO-GA Mapping",
            "CLO-GA-Mapping.docx",
            cloGaDocx,

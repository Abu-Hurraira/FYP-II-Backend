    public async Task RemoveAutoGeneratedFilesAsync(int offeredCourseId)
    {
        _draftStorage.RemoveAllAutoGeneratedFiles(offeredCourseId);

        var folder = await _context.CourseFolders
            .AsNoTracking()
            .FirstOrDefaultAsync(f => f.OfferedCourseId == offeredCourseId);
        if (folder == null)
        {
            return;
        }

        await using var connection = new SqlConnection(_connectionString);
        await connection.OpenAsync();

        var command = new SqlCommand(@"
            SELECT
                f.FileID,
                f.FileName,
                f.FilePath,
                f.Remarks,
                t.TemplateCode
            FROM CourseFolderFiles f
            INNER JOIN CourseFolderDirectories d ON d.DirectoryID = f.DirectoryID
            INNER JOIN CourseFolderTemplateItems t ON t.TemplateItemID = d.TemplateItemID
            WHERE d.CourseFolderID = @CourseFolderID;
        ", connection);
        command.Parameters.AddWithValue("@CourseFolderID", folder.CourseFolderId);

        var junk = new List<(int FileId, string FilePath)>();
        await using (var reader = await command.ExecuteReaderAsync())
        {
            while (await reader.ReadAsync())
            {
                var fileName = Convert.ToString(reader["FileName"]);
                var remarks = reader["Remarks"] == DBNull.Value ? null : Convert.ToString(reader["Remarks"]);
                var templateCode = Convert.ToString(reader["TemplateCode"]);
                if (IsJunkAutoOrSeed(remarks, fileName, templateCode))
                {
                    junk.Add((
                        Convert.ToInt32(reader["FileID"]),
                        Convert.ToString(reader["FilePath"]) ?? ""));
                }
            }
        }

        foreach (var file in junk)
        {
            FolderStoragePath.DeleteExistingFiles(_environment, file.FilePath);
            await DeleteCourseFolderFileRecordAsync(connection, file.FileId);
        }
    }

    public async Task ClearSubmittedFolderFilesAsync(int offeredCourseId)
    {
        var folder = await _context.CourseFolders
            .AsNoTracking()
            .FirstOrDefaultAsync(f => f.OfferedCourseId == offeredCourseId);
        if (folder == null)
        {
            return;
        }

        await using var connection = new SqlConnection(_connectionString);
        await connection.OpenAsync();

        var command = new SqlCommand(@"
            SELECT f.FileID, f.FilePath
            FROM CourseFolderFiles f
            INNER JOIN CourseFolderDirectories d ON d.DirectoryID = f.DirectoryID
            WHERE d.CourseFolderID = @CourseFolderID;
        ", connection);
        command.Parameters.AddWithValue("@CourseFolderID", folder.CourseFolderId);

        var files = new List<(int FileId, string FilePath)>();
        await using (var reader = await command.ExecuteReaderAsync())
        {
            while (await reader.ReadAsync())
            {
                files.Add((
                    Convert.ToInt32(reader["FileID"]),
                    Convert.ToString(reader["FilePath"]) ?? ""));
            }
        }

        foreach (var file in files)
        {
            FolderStoragePath.DeleteExistingFiles(_environment, file.FilePath);
            await DeleteCourseFolderFileRecordAsync(connection, file.FileId);
        }
    }

    public async Task<int> ClearAllSubmittedFolderFilesAsync()
    {
        var offeredCourseIds = await _context.CourseFolders
            .AsNoTracking()
            .Select(f => f.OfferedCourseId)
            .ToListAsync();

        foreach (var offeredCourseId in offeredCourseIds)
        {
            await ClearSubmittedFolderFilesAsync(offeredCourseId);
        }

        return offeredCourseIds.Count;
    }

    public async Task<int> PublishCourseFolderDataAsync(int offeredCourseId, int teacherUserId)
    {
        var oc = await _context.OfferedCourses
            .Include(x => x.Course)
            .Include(x => x.Section)
                .ThenInclude(s => s.Session)
                    .ThenInclude(s => s.Program)
            .FirstOrDefaultAsync(x => x.OfferedCourseId == offeredCourseId);

        if (oc == null)
        {
            throw new InvalidOperationException("Offered course not found.");
        }

        var existingFolder = await _context.CourseFolders
            .AsNoTracking()
            .FirstOrDefaultAsync(f => f.OfferedCourseId == offeredCourseId);
        if (existingFolder != null && IsFolderLocked(existingFolder.FolderStatus))
        {
            throw new InvalidOperationException("Folder is locked after submission.");
        }

        var folderRecord = await _folderProvisioning.EnsureMasterFolderAsync(offeredCourseId, teacherUserId);
        var programCourseId = await _permissionService.EnsureProgramCourseAsync(
            oc.Section.Session.ProgramId,
            oc.CourseId);
        var sessionId = oc.Section.SessionId;
        var permissions = await _permissionService.GetTeacherFlagsAsync(teacherUserId, programCourseId);
        var templates = await LoadTemplateItemsAsync();
        var subtitle = $"{oc.Course.CourseCode} · {oc.Course.CourseTitle} · {oc.Section.SectionName}";
        var imported = 0;

        await RemovePublishedTemplateFilesAsync(
            folderRecord.CourseFolderId,
            templates,
            "a",
            "Course Objective");

        await RemoveAllTemplateCategoryFilesAsync(
            folderRecord.CourseFolderId, templates, "b", "CLO-Task Mapping");

        var cloGaDocx = await BuildCloGaMappingDocxAsync(
            oc, programCourseId, sessionId, permissions);
        if (cloGaDocx is { Length: > 0 })
        {
            await UpsertPhysicalPdfAsync(
                folderRecord.CourseFolderId, templates, "b", teacherUserId,
                "CLO-GA Mapping",
                "CLO-GA-Mapping.docx",
                cloGaDocx,
                PublishedRemark);
            imported++;
        }

        await RemovePublishedTemplateFilesAsync(
            folderRecord.CourseFolderId,
            templates,
            "c",
            "Course Content");

        var contentsDocx = await BuildWeeklyPlanDocxAsync(
            oc, offeredCourseId, programCourseId, sessionId, permissions);
        if (contentsDocx is { Length: > 0 })
        {
            await UpsertPhysicalPdfAsync(
                folderRecord.CourseFolderId, templates, "c", teacherUserId,
                "Course Content",
                "Course Objectives Outline.docx",
                contentsDocx,
                PublishedRemark);
            imported++;
        }

        await RemovePublishedTemplateFilesAsync(
            folderRecord.CourseFolderId,
            templates,
            "d",
            "Weekly Plan");

        var weeklyDocx = await BuildWeeklyPlanDocxAsync(
            oc, offeredCourseId, programCourseId, sessionId, permissions);
        if (weeklyDocx is { Length: > 0 })
        {
            await UpsertPhysicalPdfAsync(
                folderRecord.CourseFolderId, templates, "d", teacherUserId,
                "Weekly Plan", "Weekly-Plan.docx", weeklyDocx, PublishedRemark);
            imported++;
        }

        var questionAssessments = await _context.Assessments
            .AsNoTracking()
            .Where(a => a.OfferedCourseId == offeredCourseId && a.AssessmentQuestions.Any())
            .CountAsync();
        await _assessmentFolderSync.PublishQuestionPdfsForCourseAsync(offeredCourseId, teacherUserId);
        if (questionAssessments > 0)
        {
            imported += questionAssessments;
        }

        await PublishMarksResultAndOutcomesAsync(
            offeredCourseId,
            teacherUserId,
            folderRecord.CourseFolderId,
            subtitle);
        imported++;

        try
        {
            var report = await _fcarReportService.GetFcarReportAsync(offeredCourseId, teacherUserId);
            if (!string.IsNullOrWhiteSpace(report.CatalogDescription))
            {
                var fcarPdf = FcarPdfGenerator.Generate(report);
                var storedName = $"FCAR-{oc.Course.CourseCode}-{oc.Section.SectionName}.pdf";
                await UpsertPhysicalPdfAsync(
                    folderRecord.CourseFolderId, templates, "o", teacherUserId,
                    "Complete Analysis of Course", storedName, fcarPdf, FcarRemark);
                imported++;
            }
        }
        catch (Exception)
        {
            // FCAR is optional until the teacher completes the main report fields.
        }

        await RemovePublishedTemplateFilesAsync(
            folderRecord.CourseFolderId,
            templates,
            "e",
            "Attendance Record");

        return imported;
    }


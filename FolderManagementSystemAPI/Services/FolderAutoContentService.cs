    private async Task UpsertPhysicalPdfAsync(
        int courseFolderId,
        List<TemplateItemInfo> templates,
        string templateCode,
        int teacherUserId,
        string fileCategory,
        string fileName,
        byte[] pdfBytes,
        string remarks)
    {
        var template = templates.FirstOrDefault(item =>
            item.TemplateCode.Equals(templateCode, StringComparison.OrdinalIgnoreCase));

        if (template == null)
        {
            return;
        }

        await using var connection = new SqlConnection(_connectionString);
        await connection.OpenAsync();

        var dirCommand = new SqlCommand(@"
            SELECT DirectoryID, DirectoryPath
            FROM CourseFolderDirectories
            WHERE CourseFolderID = @CourseFolderID
            AND TemplateItemID = @TemplateItemID;
        ", connection);

        dirCommand.Parameters.AddWithValue("@CourseFolderID", courseFolderId);
        dirCommand.Parameters.AddWithValue("@TemplateItemID", template.TemplateItemId);

        int directoryId;
        string directoryPath;

        await using (var reader = await dirCommand.ExecuteReaderAsync())
        {
            if (!await reader.ReadAsync())
            {
                return;
            }

            directoryId = Convert.ToInt32(reader["DirectoryID"]);
            directoryPath = Convert.ToString(reader["DirectoryPath"]) ?? "";
        }

        var existingCommand = new SqlCommand(@"
            SELECT FileID, FilePath
            FROM CourseFolderFiles
            WHERE DirectoryID = @DirectoryID
            AND FileCategory = @FileCategory
            AND (
                Remarks = @Remarks
                OR Remarks = @AutoRemark
                OR Remarks = @PublishedRemark
                OR Remarks = @FcarRemark
            );
        ", connection);

        existingCommand.Parameters.AddWithValue("@DirectoryID", directoryId);
        existingCommand.Parameters.AddWithValue("@FileCategory", fileCategory);
        existingCommand.Parameters.AddWithValue("@Remarks", remarks);
        existingCommand.Parameters.AddWithValue("@AutoRemark", AutoGeneratedRemark);
        existingCommand.Parameters.AddWithValue("@PublishedRemark", PublishedRemark);
        existingCommand.Parameters.AddWithValue("@FcarRemark", FcarRemark);

        var filesToDelete = new List<(int FileId, string FilePath)>();

        await using (var reader = await existingCommand.ExecuteReaderAsync())
        {
            while (await reader.ReadAsync())
            {
                filesToDelete.Add((
                    Convert.ToInt32(reader["FileID"]),
                    Convert.ToString(reader["FilePath"]) ?? ""));
            }
        }

        foreach (var file in filesToDelete)
        {
            FolderStoragePath.DeleteExistingFiles(_environment, file.FilePath);
            await DeleteCourseFolderFileRecordAsync(connection, file.FileId);
        }

        var safeBaseName = SanitizeFileName(fileName);
        if (!Path.HasExtension(safeBaseName))
        {
            safeBaseName += ".pdf";
        }

        var relativeFilePath = $"{directoryPath}/{safeBaseName}";
        var absoluteDirectoryPath = GetAbsolutePath(directoryPath);
        var absoluteFilePath = GetAbsolutePath(relativeFilePath);

        Directory.CreateDirectory(absoluteDirectoryPath);
        FolderStoragePath.WriteAllBytes(_environment, relativeFilePath, pdfBytes);

        var insertCommand = new SqlCommand(@"
            INSERT INTO CourseFolderFiles
            (
                DirectoryID,
                UploadedByUserID,
                FileName,
                FilePath,
                FileCategory,
                Remarks
            )
            VALUES
            (
                @DirectoryID,
                @UploadedByUserID,
                @FileName,
                @FilePath,
                @FileCategory,
                @Remarks
            );
        ", connection);

        insertCommand.Parameters.AddWithValue("@DirectoryID", directoryId);
        insertCommand.Parameters.AddWithValue("@UploadedByUserID", teacherUserId);
        insertCommand.Parameters.AddWithValue("@FileName", safeBaseName);
        insertCommand.Parameters.AddWithValue("@FilePath", relativeFilePath);
        insertCommand.Parameters.AddWithValue("@FileCategory", fileCategory);
        insertCommand.Parameters.AddWithValue("@Remarks", remarks);

        await insertCommand.ExecuteNonQueryAsync();
    }

    private async Task<List<TemplateItemInfo>> LoadTemplateItemsAsync()
    {
        var items = new List<TemplateItemInfo>();

        await using var connection = new SqlConnection(_connectionString);
        await connection.OpenAsync();

        var command = new SqlCommand(@"
            SELECT TemplateItemID, TemplateCode, FolderItemName, SortOrder
            FROM CourseFolderTemplateItems
            ORDER BY SortOrder;
        ", connection);

        await using var reader = await command.ExecuteReaderAsync();

        while (await reader.ReadAsync())
        {
            items.Add(new TemplateItemInfo
            {
                TemplateItemId = Convert.ToInt32(reader["TemplateItemID"]),
                TemplateCode = Convert.ToString(reader["TemplateCode"]) ?? "",
                FolderItemName = Convert.ToString(reader["FolderItemName"]) ?? "",
                SortOrder = Convert.ToInt32(reader["SortOrder"])
            });
        }

        return items;
    }

    private string GetAbsolutePath(string relativePath) =>
        FolderStoragePath.Resolve(_environment, relativePath);

    private static string GetPdfTitle(string templateCode) =>
        templateCode.ToLowerInvariant() switch
        {
            "a" => "Course Objectives",
            "b" => "CLO-GA Mapping",
            "c" => "Course Objectives Outline",
            "d" => "Weekly Plan",
            _ => "Course Document"
        };

    private static string SanitizeFileName(string fileName)
    {
        var invalid = Path.GetInvalidFileNameChars();
        var cleaned = new string(fileName.Select(ch => invalid.Contains(ch) ? '_' : ch).ToArray());
        return string.IsNullOrWhiteSpace(cleaned) ? "auto-content.pdf" : cleaned;
    }


    public async Task PublishMarksResultAndOutcomesAsync(
        int offeredCourseId,
        int teacherUserId,
        int? courseFolderId = null,
        string? subtitle = null)
    {
        var existingFolder = await _context.CourseFolders
            .AsNoTracking()
            .FirstOrDefaultAsync(f => f.OfferedCourseId == offeredCourseId);
        if (existingFolder != null && IsFolderLocked(existingFolder.FolderStatus))
        {
            return;
        }

        var folderRecord = courseFolderId.HasValue
            ? new CourseFolderRecord { CourseFolderId = courseFolderId.Value, OfferedCourseId = offeredCourseId }
            : await _folderProvisioning.EnsureMasterFolderAsync(offeredCourseId, teacherUserId);
        var templates = await LoadTemplateItemsAsync();

        if (string.IsNullOrWhiteSpace(subtitle))
        {
            var oc = await _context.OfferedCourses
                .Include(x => x.Course)
                .Include(x => x.Section)
                .FirstOrDefaultAsync(x => x.OfferedCourseId == offeredCourseId);
            subtitle = oc == null
                ? string.Empty
                : $"{oc.Course.CourseCode} · {oc.Course.CourseTitle} · {oc.Section.SectionName}";
        }

        var marksPdf = await BuildMarksDistributionPdfAsync(offeredCourseId, teacherUserId, subtitle);
        if (marksPdf != null)
        {
            await UpsertPhysicalPdfAsync(
                folderRecord.CourseFolderId,
                templates,
                "j",
                teacherUserId,
                "Marks Distribution and Grading",
                "marks-distribution.pdf",
                marksPdf,
                PublishedRemark);
        }

        var resultPdf = await BuildCourseResultPdfAsync(offeredCourseId, teacherUserId, subtitle);
        if (resultPdf != null)
        {
            await UpsertPhysicalPdfAsync(
                folderRecord.CourseFolderId,
                templates,
                "k",
                teacherUserId,
                "Result",
                "course-result.pdf",
                resultPdf,
                PublishedRemark);
        }

        var outcomesPdf = await BuildOutcomesAssessmentPdfAsync(offeredCourseId, teacherUserId, subtitle);
        if (outcomesPdf != null)
        {
            await UpsertPhysicalPdfAsync(
                folderRecord.CourseFolderId,
                templates,
                "l",
                teacherUserId,
                "Outcomes Assessment",
                "outcomes-assessment.pdf",
                outcomesPdf,
                PublishedRemark);
        }
    }

    public async Task<(byte[] Pdf, string FileName)> PublishSectionAsync(
        int offeredCourseId,
        int teacherUserId,
        string section)
    {
        var existingFolder = await _context.CourseFolders
            .AsNoTracking()
            .FirstOrDefaultAsync(f => f.OfferedCourseId == offeredCourseId);
        if (existingFolder != null && IsFolderLocked(existingFolder.FolderStatus))
        {
            throw new InvalidOperationException("Folder is locked after submission.");
        }

        var folderRecord = await _folderProvisioning.EnsureMasterFolderAsync(offeredCourseId, teacherUserId);
        var templates = await LoadTemplateItemsAsync();
        var oc = await _context.OfferedCourses
            .Include(x => x.Course)
            .Include(x => x.Section)
            .FirstOrDefaultAsync(x => x.OfferedCourseId == offeredCourseId)
            ?? throw new InvalidOperationException("Offered course not found.");
        var subtitle = $"{oc.Course.CourseCode} · {oc.Course.CourseTitle} · {oc.Section.SectionName}";
        var key = (section ?? string.Empty).Trim().ToLowerInvariant();

        byte[]? pdf;
        string templateCode;
        string fileCategory;
        string fileName;

        switch (key)
        {
            case "marks":
            case "marks-distribution":
                pdf = await BuildMarksDistributionPdfAsync(offeredCourseId, teacherUserId, subtitle);
                templateCode = "j";
                fileCategory = "Marks Distribution and Grading";
                fileName = "marks-distribution.pdf";
                break;
            case "result":
            case "results":
                pdf = await BuildCourseResultPdfAsync(offeredCourseId, teacherUserId, subtitle);
                templateCode = "k";
                fileCategory = "Result";
                fileName = "course-result.pdf";
                break;
            case "outcomes":
            case "assessment":
                pdf = await BuildOutcomesAssessmentPdfAsync(offeredCourseId, teacherUserId, subtitle);
                templateCode = "l";
                fileCategory = "Outcomes Assessment";
                fileName = "outcomes-assessment.pdf";
                break;
            default:
                throw new InvalidOperationException("Unknown folder section. Use marks, result, or outcomes.");
        }

        if (pdf == null || pdf.Length == 0)
        {
            throw new InvalidOperationException(
                "No data is available yet to save into the submitted folder.");
        }

        await UpsertPhysicalPdfAsync(
            folderRecord.CourseFolderId,
            templates,
            templateCode,
            teacherUserId,
            fileCategory,
            fileName,
            pdf,
            PublishedRemark);

        return (pdf, fileName);
    }

